export type StaticProduct = (typeof products)[number] & { id: string };

export function getStaticProducts(): StaticProduct[] {
  return products.map((p, i) => ({
    ...p,
    id: `static-${i + 1}`,
    createdAt: new Date(),
    updatedAt: new Date(),
  }));
}

export function getStaticProductBySlug(slug: string) {
  const product = products.find((p) => p.slug === slug);
  if (!product) return null;
  const index = products.findIndex((p) => p.slug === slug);
  return {
    ...product,
    id: `static-${index + 1}`,
    createdAt: new Date(),
    updatedAt: new Date(),
  };
}
